// Builds supabase/SETUP_NEW_PROJECT.sql — one script for a brand-new Supabase project —
// and supabase/UPGRADE_EXISTING_PROJECT.sql — for the restored original project.
// Run: node supabase/build-setup.mjs   (re-run after editing any of the parts below)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = dirname(fileURLToPath(import.meta.url))
const parts = ['schema.sql', 'workflow_tables.sql', 'job_card_logs.sql', 'quotation_module.sql', 'quotation_documents_bucket.sql', 'workflow_v2.sql', 'pricing_v1.sql', 'quotation_access_v1.sql', 'attendance_v1.sql', 'attendance_devices_v1.sql', 'quotation_allocation_v1.sql', 'lead_temperature_v1.sql', 'job_card_ongoing_v1.sql']
const section = p => `\n\n-- ┌───────────────────────────────────────────────────────────────\n-- │ ${p}\n-- └───────────────────────────────────────────────────────────────\n\n${readFileSync(join(dir, p), 'utf8').trim()}\n`

const header = `-- ═══════════════════════════════════════════════════════════════
-- GREENERGY CRM — COMPLETE SETUP FOR A NEW SUPABASE PROJECT
-- Generated by supabase/build-setup.mjs from: ${parts.join(', ')}
-- Paste everything into Supabase → SQL Editor → New query → Run.
-- Then follow SETUP-NEW-SUPABASE.md (create the CEO login, set Vercel keys).
-- ═══════════════════════════════════════════════════════════════
`
writeFileSync(join(dir, 'SETUP_NEW_PROJECT.sql'), header + parts.map(section).join(''))
console.log('Wrote supabase/SETUP_NEW_PROJECT.sql')

// The restored original project already has schema.sql, workflow_tables.sql and job_card_logs.sql
const upgradeParts = parts.slice(3)
const upHeader = `-- ═══════════════════════════════════════════════════════════════
-- GREENERGY CRM — UPGRADE FOR THE EXISTING (RESTORED) SUPABASE PROJECT
-- Generated by supabase/build-setup.mjs from: ${upgradeParts.join(', ')}
-- For a project that already has the original CRM tables (profiles, projects, job cards).
-- Existing staff, projects and job cards are kept.
-- Paste everything into Supabase → SQL Editor → New query → Run.
-- ═══════════════════════════════════════════════════════════════
`
writeFileSync(join(dir, 'UPGRADE_EXISTING_PROJECT.sql'), upHeader + upgradeParts.map(section).join(''))
console.log('Wrote supabase/UPGRADE_EXISTING_PROJECT.sql')
